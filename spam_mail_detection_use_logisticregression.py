def predict_mail(mail_text):
    if not mail_text or not mail_text.strip():
        return "Please enter a mail message."

    features = tfidf.transform([mail_text])
    prediction = model.predict(features)[0]

    if prediction == 1:
        return " Spam Mail"
    else:
        return " Non-Spam Mail"


